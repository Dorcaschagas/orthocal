// Keys whose values contain HTML markup (use innerHTML, not textContent)
const htmlKeys = new Set(['hero_h1']);

function detectLang() {
    const stored = localStorage.getItem('orthocal-lang');
    if (stored && translations[stored]) return stored;
    const browser = (navigator.language || navigator.userLanguage || 'pt-BR').toLowerCase();
    if (browser.startsWith('pt')) return 'pt-BR';
    if (browser.startsWith('es')) return 'es';
    if (browser.startsWith('en')) return 'en';
    return 'pt-BR';
}

function applyLang(lang) {
    const t = translations[lang] || translations['pt-BR'];

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) {
            if (htmlKeys.has(key)) {
                el.innerHTML = t[key];
            } else {
                el.textContent = t[key];
            }
        }
    });

    // Update <html lang> attribute
    document.documentElement.lang = lang;

    // Highlight the active switcher button
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // Persist choice
    localStorage.setItem('orthocal-lang', lang);
}

// Wire up language switcher buttons
document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.addEventListener('click', function () {
        applyLang(btn.getAttribute('data-lang'));
    });
});

// Apply language on page load
applyLang(detectLang());


