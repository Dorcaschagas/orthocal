// Intersection Observer para animações suaves
const observer = new IntersectionObserver((entries) => {
    entries.forEach(e => {
        if (e.isIntersecting) {
            e.target.style.opacity = '1';
            e.target.style.transform = 'translateY(0)';
        }
    });
}, { threshold: 0.1 });

document.querySelectorAll('.benefit-card, .dl-card').forEach(el => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(24px)';
    el.style.transition = 'opacity .5s ease, transform .5s ease';
    observer.observe(el);
});

// ── Carrossel de reviews ──
const track = document.getElementById('reviewTrack');
const dotsContainer = document.getElementById('reviewDots');
const cards = track.querySelectorAll('.review-card');
const cardW = () => cards[0].offsetWidth + 24; // largura + gap
const visible = () => Math.floor(track.parentElement.offsetWidth / cardW());
const total = cards.length;
let current = 0;
let autoTimer;

// Cria dots
const numDots = () => total - visible() + 1;
function buildDots() {
    dotsContainer.innerHTML = '';
    for (let i = 0; i < numDots(); i++) {
        const d = document.createElement('button');
        d.type = 'button';
        d.className = 'carousel-dot' + (i === current ? ' active' : '');
        d.addEventListener('click', () => goTo(i));
        dotsContainer.appendChild(d);
    }
}

function goTo(idx) {
    const max = Math.max(0, total - visible());
    current = Math.max(0, Math.min(idx, max));
    track.style.transform = `translateX(-${current * cardW()}px)`;
    dotsContainer.querySelectorAll('.carousel-dot').forEach((d, i) => {
        d.classList.toggle('active', i === current);
    });
}

function next() { goTo(current + 1 >= numDots() ? 0 : current + 1); }
function prev() { goTo(current - 1 < 0 ? numDots() - 1 : current - 1); }

function startAuto() { autoTimer = setInterval(next, 3500); }
function stopAuto() { clearInterval(autoTimer); }

document.querySelector('.carousel-btn.next').addEventListener('click', () => { stopAuto(); next(); startAuto(); });
document.querySelector('.carousel-btn.prev').addEventListener('click', () => { stopAuto(); prev(); startAuto(); });

// swipe touch
let touchX = 0;
track.addEventListener('touchstart', e => { touchX = e.touches[0].clientX; stopAuto(); });
track.addEventListener('touchend', e => {
    const diff = touchX - e.changedTouches[0].clientX;
    if (Math.abs(diff) > 40) diff > 0 ? next() : prev();
    startAuto();
});

buildDots();
startAuto();
window.addEventListener('resize', () => { buildDots(); goTo(0); });